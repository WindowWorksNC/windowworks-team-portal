  async function submitModule(m) {
    if (S.busy) return;
    var alertEl = el('tr-quiz-alert');
    var btn = el('tr-submit');
    var qs = m.quiz || [];

    var results = [], unanswered = [];
    qs.forEach(function (q, qi) {
      var resp = readResponse(q, qi);
      var empty = (resp.value === null) ||
        (Array.isArray(resp.value) && (!resp.value.length || resp.value.indexOf(null) >= 0)) ||
        (typeof resp.value === 'string' && !resp.value);
      if (empty) unanswered.push(qi + 1);
      results.push({ q: q, qi: qi, resp: resp, grade: gradeOne(q, resp) });
    });

    if (unanswered.length) {
      if (alertEl) {
        alertEl.innerHTML = '<div class="alert alert-error">Answer every question before submitting. ' +
          'Missing: ' + unanswered.join(', ') + '.</div>';
      }
      return;
    }

    S.busy = true;
    if (btn) { btn.disabled = true; btn.textContent = 'Submitting...'; }

    var score = 0, autoMax = 0, pending = 0;
    results.forEach(function (r) {
      if (r.grade.auto) { score += r.grade.score; autoMax += r.grade.max; }
      else pending += r.grade.max;
    });
    var maxTotal = autoMax + pending;
    var attempt = (S.done[m.id] ? S.done[m.id].attempt : 0) + 1;

    try {
      // Read each header row once, not once per question.
      var dr = await api({ action: 'read', tab: TAB_RESP });
      if (!dr || !dr.success || !dr.data || !dr.data.length) throw new Error('responses header');
      var rc = cols(dr.data[0]);
      var rWidth = dr.data[0].length;

      // Per-question rows first, so a partial failure still leaves the answers.
      for (var i = 0; i < results.length; i++) {
        var r = results[i];
        var row = buildRow(rWidth, rc, [
          ['Employee', S.employee],
          ['Module ID', m.id],
          ['Module Title', m.title],
          ['Attempt', attempt],
          ['Question', r.q.q || ''],
          ['Type', r.q.type || ''],
          ['Response', r.resp.text],
          ['Auto Score', r.grade.auto ? r.grade.score : ''],
          ['Max Points', r.grade.max],
          ['Needs Review', r.grade.auto ? '' : 'Yes'],
          ['Submitted', todayStr()]
        ]);
        await api({ action: 'append', tab: TAB_RESP, row: JSON.stringify(row) });
      }

      var dd = await api({ action: 'read', tab: TAB_DONE });
      if (!dd || !dd.success || !dd.data || !dd.data.length) throw new Error('completions header');
      var dc = cols(dd.data[0]);
      var drow = buildRow(dd.data[0].length, dc, [
        ['Employee', S.employee],
        ['Module ID', m.id],
        ['Module Title', m.title],
        ['Week', m.week === null || m.week === undefined ? '' : m.week],
        ['Score', score],
        ['Max Points', maxTotal],
        ['Awaiting Review', pending],
        ['Attempt', attempt],
        ['Completed', todayStr()]
      ]);
      await api({ action: 'append', tab: TAB_DONE, row: JSON.stringify(drow) });

      if (pending) await emailReview(m, results, attempt);

      S.done[m.id] = {
        score: score, max: maxTotal, pending: pending,
        attempt: attempt, completed: todayStr()
      };

      showFeedback(results);
      var head = document.querySelector('.tr-quizhead .tr-leave');
      if (head) { head.textContent = 'Back to your path'; }
      if (alertEl) {
        alertEl.innerHTML = '<div class="alert alert-success">Submitted. ' + score + ' of ' + autoMax +
          ' on the auto-graded questions' +
          (pending ? ', plus ' + pending + ' points now with Rose and Justin for review.' : '.') + '</div>';
      }
      if (btn) { btn.textContent = 'Submitted'; }
    } catch (e) {
      console.error(e);
      if (alertEl) alertEl.innerHTML = '<div class="alert alert-error">Could not save your quiz. Please try again.</div>';
      if (btn) { btn.disabled = false; btn.textContent = 'Submit Quiz'; }
    }
    S.busy = false;
  }

  function showFeedback(results) {
    results.forEach(function (r) {
      var fb = el('trq-fb-' + r.qi);
      if (!fb) return;
      if (!r.grade.auto) {
        fb.innerHTML = '<span class="pill pill-yellow">Sent for review</span>';
        return;
      }
      var tag = r.grade.correct
        ? '<span class="pill pill-approved">Correct</span>'
        : '<span class="pill pill-denied">Not quite</span>';
      fb.innerHTML = tag + (r.grade.why ? '<div class="tr-why">' + inlineMd(r.grade.why.trim()) + '</div>' : '');
    });
  }

  async function emailReview(m, results, attempt) {
    var lines = results.filter(function (r) { return !r.grade.auto; }).map(function (r) {
      return '<p><strong>' + esc(r.q.q || '') + '</strong><br>' +
        '<em>' + esc(r.resp.text || '(blank)') + '</em><br>' +
        'Worth ' + r.grade.max + ' points.</p>';
    });
    var body = '<p>' + esc(S.employee) + ' submitted <strong>' + esc(m.title) +
      '</strong> (' + esc(m.id) + '), attempt ' + attempt + '.</p>' +
      '<p>' + lines.length + ' answer' + (lines.length === 1 ? '' : 's') + ' need review:</p>' +
      lines.join('') +
      '<p>Open the Training Progress tab in the portal to record a decision.</p>';
    try {
      await api({
        action: 'send_email',
        to_key: 'training',
        subject: 'Training review: ' + S.employee + ' - ' + m.title,
        body: body
      });
    } catch (e) { console.error('review email failed', e); }
  }

