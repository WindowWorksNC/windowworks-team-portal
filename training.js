  /* ---------- grading ---------- */

  function readResponse(q, qi) {
    var name = 'trq' + qi;
    var t = q.type;
    if (t === 'multi_select') {
      var picked = [];
      Array.prototype.forEach.call(document.getElementsByName(name), function (n) {
        if (n.checked) picked.push(Number(n.value));
      });
      return { value: picked, text: picked.map(function (i) { return (q.options || [])[i]; }).join('; ') };
    }
    if (t === 'matching') {
      var sels = document.querySelectorAll('select[name="' + name + '"]');
      var vals = [], txt = [];
      Array.prototype.forEach.call(sels, function (s) {
        var v = s.value === '' ? null : Number(s.value);
        vals.push(v);
        txt.push((q.rows || [])[Number(s.getAttribute('data-row'))] + ' = ' +
          (v === null ? '(blank)' : (q.columns || [])[v]));
      });
      return { value: vals, text: txt.join('; ') };
    }
    if (t === 'short_answer' || t === 'file_upload') {
      var f = el(name);
      var v = f ? (f.value || '').trim() : '';
      return { value: v, text: v };
    }
    var chosen = null;
    Array.prototype.forEach.call(document.getElementsByName(name), function (n) {
      if (n.checked) chosen = Number(n.value);
    });
    var label = chosen === null ? '' : (q.options || [])[chosen];
    if (t === 'image_options' && chosen !== null) label = 'Option ' + (chosen + 1) + ' (' + label + ')';
    return { value: chosen, text: label || '' };
  }

  function gradeOne(q, resp) {
    var max = Number(q.points) || 0;
    if (!q.k) return { auto: false, score: 0, max: max, why: '' };
    var k = decKey(q.k);
    if (!k) return { auto: false, score: 0, max: max, why: '' };
    var ok = false;
    if (q.type === 'multi_select') ok = sameSet(resp.value, k.a || []);
    else if (q.type === 'matching') {
      var want = k.a || [];
      ok = Array.isArray(resp.value) && resp.value.length === want.length &&
        resp.value.every(function (v, i) { return v === want[i]; });
    } else ok = (resp.value !== null && resp.value === k.a);
    return { auto: true, correct: ok, score: ok ? max : 0, max: max, why: k.w || '' };
  }

